/**
 * Neomatrix — generate the PROVEN node-id set for the explorer's
 * "Proven engines" view (NI-5). PURE NODE, build-time only.
 *
 * A semantic node is "proven" iff it is an engine/orchestrator whose `file`
 * is a calc-audit registry `sourcePath` (i.e. it has a fixture proving it).
 * Emitted as a committed static JSON so the admin API can tag nodes WITHOUT a
 * runtime filesystem read (Vercel serverless safe). Regenerate when engines or
 * the graph change: `npm run neomatrix:proven`.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dir, '../..');
const SEM = resolve(ROOT, 'docs/financial-logic/graph/financial-graph.json');
const OUT = resolve(ROOT, 'docs/financial-logic/graph/proven-engines.json');
const REG_DIR = resolve(ROOT, 'lib/calc-audit/engines');

function provenSourcePaths() {
  const sps = new Set();
  const walk = (dir) => {
    for (const ent of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, ent.name);
      if (ent.isDirectory()) walk(p);
      else if (ent.name.endsWith('.ts')) {
        const src = readFileSync(p, 'utf8');
        const re = /name:\s*'([a-z][a-zA-Z0-9_.]+)'/g;
        let m;
        while ((m = re.exec(src))) {
          const tail = src.slice(m.index, m.index + 700);
          const sp = /sourcePath:\s*'([^']+)'/.exec(tail);
          if (sp) sps.add(sp[1]);
        }
      }
    }
  };
  walk(REG_DIR);
  return sps;
}

const sem = JSON.parse(readFileSync(SEM, 'utf8'));
const proven = provenSourcePaths();
const ids = sem.nodes
  .filter((n) => (n.kind === 'engine' || n.kind === 'orchestrator') && n.file && proven.has(n.file))
  .map((n) => n.id)
  .sort();
writeFileSync(OUT, JSON.stringify({ generatedNote: 'Auto-generated by scripts/neomatrix/generate-proven-set.mjs — do not hand-edit. Node ids that are PROVEN (engine/orchestrator with a calc-audit fixture). Used by the explorer "Proven engines" view (NI-5).', count: ids.length, provenNodeIds: ids }, null, 2) + '\n');
console.log(`proven node ids: ${ids.length} → ${OUT.replace(ROOT + '/', '')}`);
